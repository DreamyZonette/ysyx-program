static const uint32_t img[] = {
    // 1. 整数计算指令 (除ADDI外)
    0x00500093,        // ADDI x1, x0, 5       -> x1 = 5
    0xffd08113,        // ADDI x2, x1, -3      -> x2 = 2
    0x002081b3,        // ADD x3, x1, x2       -> x3 = 5 + 2 = 7
    0x40210233,        // SUB x4, x2, x2       -> x4 = 2 - 2 = 0
    0x0030a2b3,        // SLT x5, x1, x3       -> x5 = (5 < 7) ? 1 : 0
    0x003135b3,        // SLTU x11, x2, x3     -> x11 = (2 < 7) ? 1 : 0 (无符号比较)
    0x00114633,        // XOR x12, x2, x1      -> x12 = 2 XOR 5
    0x001175b3,        // AND x11, x2, x1      -> x11 = 2 AND 5
    0x001165b3,        // OR x11, x2, x1       -> x11 = 2 OR 5

    // 2. 移位指令
    0x00115733,        // SLL x14, x2, x1      -> x14 = 2 << 5
    0x401157b3,        // SRA x15, x2, x1      -> x15 = 2 >> 5 (算术右移)
    0x40115833,        // SRL x16, x2, x1      -> x16 = 2 >> 5 (逻辑右移)

    // 3. 立即数变种指令
    0x00a00693,        // ADDI x13, x0, 10     -> x13 = 10
    0x00a0c713,        // SLLI x14, x1, 10     -> x14 = 5 << 10
    0x40a0d793,        // SRAI x15, x1, 10     -> x15 = 5 >> 10 (算术)
    0x00a0d813,        // SRLI x16, x1, 10     -> x16 = 5 >> 10 (逻辑)
    0x00a0c593,        // SLLI x11, x1, 10     -> 另一种立即数移位

    // 4. 内存访问指令 (Load/Store) - 假设内存从某个地址开始可用
    0x0000a017,        // AUIPC x0, 0x0000a000 -> 将高位立即数加到PC，用于地址计算 (此例中目标为x0，可能需调整)
    // 假设x10是某个可用的临时地址寄存器，需要先为其设置一个有效的内存地址
    0x00000517,        // AUIPC x10, 0          -> x10 = PC + (0 << 12)
    0x00050513,        // ADDI x10, x10, 0      -> x10 = x10 + 0 (此处地址需根据实际情况调整)
    0x00552023,        // SW x5, 0(x10)         -> 将x5的值存储到[x10 + 0]的内存地址
    0x00052683,        // LW x13, 0(x10)        -> 从[x10 + 0]的内存地址加载数据到x13

    // 5. 控制转移指令
    0x0040006f,        // JAL x0, label0        -> 跳转到label0 (偏移量需计算)
    0x00000013,        // NOP                   -> 无操作 (ADDI x0, x0, 0)
    // label0:
    0xfe000ae3,        // BEQ x0, x0, -12       -> 如果x0 == x0 (总是真)，则向前跳转-12条指令（实际地址需计算）
    0x00100073,        // EBREAK                -> 进入调试模式，常用于模拟器或调试器中停止执行

    // 6. 其他指令
    0x00000073,        // ECALL                 -> 系统调用
    0x00100073,        // EBREAK                -> 再次break，作为测试结束标志
};

void init_isa() {
  /* Load built-in image. */
  memcpy(guest_to_host(RESET_VECTOR), img, sizeof(img));
}